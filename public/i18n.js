let currentLocale = 'zh';

export function getLocale() {
  try {
    const saved = localStorage.getItem('nanomesh-lang');
    if (saved && (saved === 'zh' || saved === 'en')) {
      currentLocale = saved;
      return saved;
    }
  } catch (e) {}
  return currentLocale;
}

export function setLocale(locale) {
  if (translations[locale]) {
    currentLocale = locale;
    try {
      localStorage.setItem('nanomesh-lang', locale);
    } catch (e) {}
    applyTranslations();
    window.dispatchEvent(new CustomEvent('nanomesh-locale-changed', { detail: { locale } }));
  }
}

export function t(key, params = {}) {
  const loc = getLocale();
  const dict = translations[loc] || translations['zh'];
  let text = dict[key] !== undefined ? dict[key] : (translations['en'] && translations['en'][key] !== undefined ? translations['en'][key] : key);
  for (const [k, v] of Object.entries(params)) {
    text = text.replace(`{${k}}`, v);
  }
  return text;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = t(key);
    } else {
        if (el.hasAttribute('data-i18n-html')) {
            el.innerHTML = t(key);
        } else if (el.children.length > 0) {
            for (let child of el.childNodes) {
                if (child.nodeType === Node.TEXT_NODE && child.textContent.trim().length > 0) {
                    child.textContent = ' ' + t(key);
                }
            }
        } else {
            el.textContent = t(key);
        }
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = t(key);
  });
}

